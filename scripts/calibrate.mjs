// Notary — certificate calibration harness (split-conformal, Monte-Carlo).
// Per-tool actual token costs are modelled lognormal(median_t, DISPERSION) with
// median_t = p95_t / e^{z95·σ}. This harness simulates synthetic episodes per surface size,
// measures the empirical breach rate of the Bonferroni certificate, then fits a single
// conformal inflation factor on a calibration half and verifies it on a held-out half.
// HONEST SCOPE: calibration is under the fitted model — plug in production telemetry to
// make the guarantee empirical. The harness is the deliverable; the data swap is a roadmap item.
// Run: npm run calibrate
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { TOOL_REGISTRY } from '../src/core/registry.js';
import { issueCertificate } from '../src/core/certificate.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SEED = 20261124;
let s = SEED >>> 0;
const rand = () => (s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296;
const randn = () => { // Box–Muller
  let u = 0, v = 0;
  while (u === 0) u = rand();
  while (v === 0) v = rand();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
};

const DISPERSION = 0.85, Z95 = 1.6448536269514722, ALPHA = 0.05;
const medians = TOOL_REGISTRY.map(t => t.p95 / Math.exp(Z95 * DISPERSION));
const sampleActual = i => Math.exp(Math.log(medians[i]) + DISPERSION * randn());

// one episode: pick surface size n, draw n distinct tools, compute bound & actual
const EPISODES = 40000;
const episodes = { cal: [], test: [] };
for (let k = 0; k < EPISODES; k++) {
  const nTools = 1 + Math.floor(rand() * 8);
  const idxs = new Set();
  while (idxs.size < nTools) idxs.add(Math.floor(rand() * TOOL_REGISTRY.length));
  const tools = [...idxs].map(i => TOOL_REGISTRY[i]);
  const idxArr = [...idxs];
  const bound = issueCertificate(tools, ALPHA).bound;
  const stochBound = issueCertificate(tools, ALPHA).stochastic;
  const det = issueCertificate(tools, ALPHA).deterministic;
  const actual = det + idxArr.reduce((sum, i) => sum + sampleActual(i), 0);
  const ep = { n: nTools, bound, stoch: stochBound, det, actual, ratio: (actual - det) / stochBound };
  (k % 2 === 0 ? episodes.cal : episodes.test).push(ep);
}
const breach = (eps, infl) => eps.filter(e => e.det + e.stoch * (typeof infl === 'function' ? infl(e) : infl) < e.actual).length / eps.length;
const q = (arr, p) => { const a = [...arr].sort((x, y) => x - y); return a[Math.min(a.length - 1, Math.ceil(p * a.length) - 1)]; };
const inflations = {};
for (let n = 1; n <= 8; n++) inflations[n] = q(episodes.cal.filter(e => e.n === n).map(e => e.ratio), 1 - ALPHA);
const inf = n => inflations[Math.min(n, 8)];

console.log('surface size | Bonferroni breach | conformal-tightened breach (held-out half)');
for (let n = 1; n <= 8; n++) {
  const testN = episodes.test.filter(e => e.n === n);
  if (!testN.length) continue;
  console.log(`  n=${n}        |   ${(breach(testN, 1) * 100).toFixed(2).padStart(6)}%        |   ${(breach(testN, inf(n)) * 100).toFixed(2).padStart(6)}%   (×${inf(n).toFixed(3)})`);
}
const overallTestBonf = breach(episodes.test, 1);
const overallTestConf = breach(episodes.test, e => inf(e.n));
const perSize = Object.fromEntries(Object.entries(inflations).map(([k, v]) => [k, +v.toFixed(6)]));
console.log(`\noverall test-half breach: Bonferroni ${(overallTestBonf * 100).toFixed(2)}% → per-size conformal: ${(overallTestConf * 100).toFixed(2)}% (target ≤ ${ALPHA * 100}%)`);

const out = `// GENERATED by scripts/calibrate.mjs — do not edit by hand. Recalibrate: npm run calibrate
// Per-surface-size split-conformal factors applied to the stochastic tail of the certificate.
// Fitted on ${episodes.cal.length} synthetic episodes (seeded), verified on ${episodes.test.length} held-out episodes.
export const CERTIFICATE_CALIBRATION = {
  kind: 'notary/cert-calibration',
  version: 2,
  fittedAt: ${JSON.stringify(new Date().toISOString())},
  dispersion: ${DISPERSION},
  alpha: ${ALPHA},
  inflations: ${JSON.stringify(perSize)},
  episodes: { calibration: ${episodes.cal.length}, test: ${episodes.test.length} },
  empiricalBreach: { bonferroniTest: ${overallTestBonf}, conformalTest: ${overallTestConf} },
  note: 'Calibration under the fitted lognormal model — swap in production token telemetry for an empirical guarantee (roadmap).',
};
`;
writeFileSync(join(root, 'src/core/cert-calibration.js'), out);
console.log('wrote src/core/cert-calibration.js');
